const near = (x, target, tol) => Math.abs(x - target) <= tol;

// Температура замерзания смеси «антифриз + вода» в зависимости от доли концентрата (по объёму),
// для этиленгликоля по объёму (Engineering Toolbox, таблица GlycoChill)
const FREEZE = [[0, 0], [10, -3.4], [20, -8], [30, -14], [40, -24], [50, -37], [60, -52], [65, -52], [70, -50], [80, -46], [90, -30], [100, -13]];
export function freezePoint(c) {
  for (let i = 0; i < FREEZE.length - 1; i++) {
    const [a, ta] = FREEZE[i], [b, tb] = FREEZE[i + 1];
    if (c <= b) return ta + ((tb - ta) * (c - a)) / (b - a);
  }
  return FREEZE[FREEZE.length - 1][1];
}

